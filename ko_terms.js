/**
 * 근육 이외의 구조(뼈·신경·혈관·장기)를 위치로 부위에 배정한다.
 * c: 구조 경계상자의 중심(미터, y 위쪽, z 앞쪽). 기준값은 기본 모델의 뼈 위치에서 잰 것.
 */
export function regionOf(c, name = '') {
  const ax = Math.abs(c.x), y = c.y, z = c.z;
  if (y > 0.7 && y < 1.36 && ax > 0.145 + (1.35 - y) * 0.075) return '팔';
  if (y > 0.55 && ax > 0.215) return '팔';   // fingertips hang below the hip line
  if (y >= 1.49 || (y >= 1.455 && z >= 0.1)) return '얼굴·머리';
  if (y >= 1.37) return '목';
  if (/vertebra|intervertebral|spinal|cauda equina/i.test(name) && y >= 0.9) return '등';
  if (y >= 1.14) return z < 0.075 ? '등' : '가슴';
  if (y >= 0.96) return z < 0.075 ? '등' : '복부';
  if (y >= 0.76 || (y > 0.66 && ax < 0.035)) return '골반';
  return '다리';
}

/** 신경계 레이어 안의 구조를 말초신경(nerve) / 뇌·척수(brain) / 안구·귀(sense)로 나눈다. */
export function nervousKind(name) {
  if (/nerve|plexus|branch|sympathetic|cauda equina|chorda/i.test(name) && !/nucleus|choroid/i.test(name)) return 'nerve';
  if (/eye|cornea|lens|iris|retina|sclera|vitreous|lacrimal|zonular|^ear$|cochlea$|vestibule|tympanic|auditory tube/i.test(name)) return 'sense';
  return 'brain';
}

